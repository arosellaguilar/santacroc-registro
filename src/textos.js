export function detectarIdioma() {
  const preferido = (navigator.languages?.[0] || navigator.language || '').toLowerCase()
  if (preferido.startsWith('ca')) return 'ca'
  if (preferido.startsWith('es')) return 'es'
  return 'en'
}

